// Which settings the plugin form opens with (foundations-spec.md section 6.3, "Saved settings").
// Settings are saved inside each Figma file, so every file keeps its own.
// Pure functions, no Figma API: src/figma.ts reads the file and saves the settings.

import type { Inputs } from "./foundations.ts";

// The collections the plugin makes. Variables in other collections are not its tokens.
const TOKEN_COLLECTIONS = ["Primitives", "Theme", "Appearance", "ColorScheme"];

// True when at least one variable is in a collection the plugin makes.
// collectionOfEachVariable: the collection name of every variable in the file.
export function fileHasTokens(collectionOfEachVariable: (string | undefined)[]): boolean {
  return collectionOfEachVariable.some((name) => TOKEN_COLLECTIONS.includes(name ?? ""));
}

// Settings as saved in the file. Nothing saved, or text that cannot be read, gives null.
export function readSavedInputs(text: string): Inputs | null {
  try {
    return text ? JSON.parse(text) : null;
  } catch {
    return null;
  }
}

// The settings the form opens with. null means the default settings.
// - No tokens in the file: nothing to continue from, so the form starts fresh.
// - Tokens and saved settings: this file's settings.
// - Tokens but no settings in the file: it was generated by an earlier version of the plugin, which kept one
//   copy of the settings per user. That copy is the best guess, so the user does not lose them.
export function inputsToShow(hasTokens: boolean, fileInputs: Inputs | null, olderInputs: Inputs | null): Inputs | null {
  if (!hasTokens) return null;
  return fileInputs ?? olderInputs ?? null;
}
